/**
 * hub-builder-3d.js - the 3D stage for the Tarkov weapon builder (T2 pilot).
 *
 * WHAT THIS IS
 * ------------
 * A UMD module (global: PilotHubBuilder3D) that renders a build tree as an
 * actual assembled weapon: a self-modelled M4A1 chassis GLB with named socket
 * nodes, plus generic archetype part GLBs that get parented under those
 * sockets. Swap the magazine in the 2D tree and the magazine MOVES here.
 *
 * It is deliberately standalone: it never imports hub-builder.js, never reads
 * the DOM outside its own container, and never touches the 2D composite. The
 * only contract is mount()/update()/socketScreenPositions() below.
 *
 * ON-DEMAND BY DESIGN
 * -------------------
 * Nothing here loads three.js until mount() is called. js/vendor/three-bundle.js
 * (~768 kB min / ~197 kB gz) is injected as a <script> the first time the 3D
 * toggle is pressed and is served from /apps/, which make-sw.mjs excludes from
 * the precache - so a player who never presses the toggle never pays for it.
 *
 * RENDER BUDGET
 * -------------
 * Renders ON DEMAND only. There is no always-on rAF: the loop starts on a
 * change and stops as soon as OrbitControls damping settles. Nothing is
 * allocated per frame - the projection scratch vector, the raycaster and the
 * pointer vector are all module-level singletons.
 *
 * LEGAL
 * -----
 * Every mesh it loads is generated by 3d/blender/*.py from published real-world
 * firearm dimensions. No Battlestate Games asset is read, shipped or referenced.
 * See 3d/LICENSE.md.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.PilotHubBuilder3D = factory();
}(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  // --------------------------------------------------------------------------
  // where we live. The mount is served from /apps/tarkov/ in prod and from
  // whatever the test server maps in dev, so derive it from our own <script>
  // src rather than hard-coding a path that only holds in one of the two.
  // --------------------------------------------------------------------------
  var SELF = (function () {
    try {
      if (typeof document === 'undefined') return '';
      var s = document.currentScript;
      if (!s) {
        var all = document.getElementsByTagName('script');
        for (var i = all.length - 1; i >= 0; i--) {
          if (/hub-builder-3d\.js/.test(all[i].src || '')) { s = all[i]; break; }
        }
      }
      if (!s || !s.src) return '';
      return String(s.src).replace(/js\/hub-builder-3d\.js.*$/, '');
    } catch (e) { return ''; }
  }());

  var cfg = {
    base: SELF,                      // ".../tarkov-mount/" (trailing slash)
    bundle: 'js/vendor/three-bundle.js',
    manifest: '3d/manifest.json',
    glb: '3d/glb/',
  };

  function configure(next) { for (var k in (next || {})) cfg[k] = next[k]; }
  function url(rel) { return cfg.base + rel; }

  // --------------------------------------------------------------------------
  // PURE: slot keys + archetype mapping. Mirrors PilotHubBuilder.slotKey
  // exactly - if the two ever drift, a part silently stops fitting.
  // --------------------------------------------------------------------------
  var SLOT_PREFIXES = ['pistol', 'stock', 'mount', 'tactical', 'charge', 'camora',
    'equipment', 'scope', 'muzzle', 'sight_front', 'sight_rear', 'magazine',
    'foregrip', 'handguard', 'barrel', 'reciever', 'gas_block', 'launcher',
    'bipod', 'nvg', 'flashlight'];

  function slotKey(nameId) {
    var s = String(nameId || '').toLowerCase().replace(/^mod_/, '').replace(/_\d+$/, '');
    for (var i = 0; i < SLOT_PREFIXES.length; i++) {
      if (s.indexOf(SLOT_PREFIXES[i]) === 0) {
        return SLOT_PREFIXES[i] === 'pistol' ? 'pistol_grip' : SLOT_PREFIXES[i];
      }
    }
    return s;
  }

  function lastSeg(path) {
    var p = String(path || '');
    var i = p.lastIndexOf('/');
    return i < 0 ? p : p.slice(i + 1);
  }

  // item -> archetype key, per manifest.mapping.rules. Returns null for "no
  // archetype", which the caller turns into a ghost.
  function resolveArchetype(manifest, nameId, item, gun) {
    if (!manifest) return null;
    var platform = gun && gun.platform;
    var caliber = gun && gun.caliber;
    var key = slotKey(nameId);
    var arch = manifest.archetypes || {};
    var cats = manifest.categories || {};
    var parents = manifest.categoryParents || {};
    var name = String((item && (item.n || item.name)) || '').toLowerCase();
    var shortName = String((item && (item.s || item.shortName)) || '').toLowerCase();
    var hay = name + ' ' + shortName;

    // the item's category chain, as NAMES
    var chain = [];
    var c = item && (item.cat || item.category);
    var guard = 0;
    while (c && guard++ < 12) {
      if (cats[c]) chain.push(cats[c]);
      c = parents[c] || null;
    }

    var best = null, bestScore = 0;
    Object.keys(arch).forEach(function (k) {
      var a = arch[k];
      if (!a || (a.fitsSlots || []).indexOf(key) < 0) return;
      // PLATFORM GATE: an AR handguard must never land on an AK, and an AK dust
      // cover must never land on an M4. The two families do not even agree on
      // what mod_reciever MEANS (upper receiver vs dust cover), so a keyword
      // score alone would happily cross them. Archetypes with no platform -
      // optics, foregrip, light - are shared on purpose.
      if (a.platform && platform && a.platform !== platform) return;
      // CALIBER GATE: magazines only.
      if (a.calibers && caliber && a.calibers.indexOf(caliber) < 0) return;
      var score = 0;
      var matched = false;
      (a.categoryMatch || []).forEach(function (cm) {
        if (chain.indexOf(cm) >= 0) { score += 100; matched = true; }
      });
      // Keywords outweigh a category hit ON PURPOSE. Tarkov files a 60-round
      // drum under the plain "Magazine" category, exactly like a STANAG box, so
      // when both archetypes claim the same category the NAME is the only thing
      // that can tell them apart - and at +10 it could not. Verified against the
      // live M4A1 magazine list (24 rows) in the real build.
      (a.keywords || []).forEach(function (kw) {
        if (kw && hay.indexOf(kw) >= 0) { score += 60; matched = true; }
      });
      if (!matched) return;
      score += (a.priority || 0);
      if (score > bestScore) { bestScore = score; best = k; }
    });
    return bestScore > 0 ? best : null;
  }

  // --------------------------------------------------------------------------
  // lazy loads
  // --------------------------------------------------------------------------
  var threePromise = null;
  function loadThree() {
    if (typeof globalThis !== 'undefined' && globalThis.PilotThree) {
      return Promise.resolve(globalThis.PilotThree);
    }
    if (threePromise) return threePromise;
    threePromise = new Promise(function (res, rej) {
      var s = document.createElement('script');
      s.src = url(cfg.bundle);
      s.async = true;
      s.onload = function () {
        if (globalThis.PilotThree) res(globalThis.PilotThree);
        else rej(new Error('three bundle loaded but PilotThree is undefined'));
      };
      s.onerror = function () { rej(new Error('failed to load ' + s.src)); };
      document.head.appendChild(s);
    });
    return threePromise;
  }

  var manifestPromise = null;
  var manifestCache = null;
  function loadManifest() {
    if (manifestCache) return Promise.resolve(manifestCache);
    if (manifestPromise) return manifestPromise;
    manifestPromise = fetch(url(cfg.manifest), { cache: 'force-cache' })
      .then(function (r) {
        if (!r.ok) throw new Error('manifest ' + r.status);
        return r.json();
      })
      .then(function (m) { manifestCache = m; return m; });
    return manifestPromise;
  }

  // gun ids with 3D. Safe to call before anything is loaded (returns false
  // until the manifest lands, then the real answer).
  function supports(gunId) {
    return !!(manifestCache && manifestCache.guns && manifestCache.guns[gunId]);
  }
  function ready() { return loadManifest().then(function () { return true; }); }

  // --------------------------------------------------------------------------
  // GLB cache (per archetype key / gun key) - fetched once, cloned per use.
  // --------------------------------------------------------------------------
  var glbCache = Object.create(null);

  // Minimum LINEAR base-colour luminance. The blockout is authored in gunmetal
  // (0.038-0.055 linear), which on the builder's near-black plate renders as a
  // silhouette you cannot read on a phone outdoors. Lifting to 0.10 linear is
  // ~0.35 sRGB: still obviously dark polymer/steel, but legible at a glance.
  // Done once per cached GLB, before any clone, so it costs nothing per swap.
  // 0.125, raised from 0.10 when the AK furniture was finally taken down to
  // real bakelite: with two thirds of an AK's silhouette now legitimately dark,
  // the receiver had to carry the readability on its own. Furniture is exempt
  // (see FURNITURE below), so this only ever lifts gunmetal and black polymer.
  var MIN_BASE_LUM = 0.125;

  // FURNITURE IS EXEMPT FROM THE LIFT. The lift exists so gunmetal and black
  // polymer are not a silhouette on the near-black plate - but applied to the
  // AK's plum/bakelite and tan furniture it pushed them to salmon, which is a
  // colour no rifle has ever worn. Wood and plum are ALREADY well above the
  // silhouette threshold; they never needed it. Material names survive the
  // Blender -> glTF export (verified: ak_mag_30.glb carries "PolymerPlum"), so
  // the exemption keys off the name the generator gave it.
  var FURNITURE = { PolymerPlum: 1, PolymerTan: 1, PolymerWood: 1 };

  function liftMaterials(T, scene) {
    scene.traverse(function (o) {
      var m = o.material;
      if (!m) return;
      (Array.isArray(m) ? m : [m]).forEach(function (mm) {
        if (!mm || !mm.color || (mm.userData && mm.userData.__lifted)) return;
        mm.userData = mm.userData || {};
        mm.userData.__lifted = 1;
        if (FURNITURE[mm.name]) return;            // keep the real tone
        var c = mm.color;
        var l = 0.2126 * c.r + 0.7152 * c.g + 0.0722 * c.b;
        if (l > 0 && l < MIN_BASE_LUM) {
          var k = MIN_BASE_LUM / l;
          c.setRGB(Math.min(1, c.r * k), Math.min(1, c.g * k), Math.min(1, c.b * k));
        }
        // a mirror-rough metal under one key light is just black
        if (mm.metalness != null && mm.metalness > 0.5 && mm.roughness != null) {
          mm.roughness = Math.min(mm.roughness, 0.40);
        }
      });
    });
  }

  function loadGlb(THREE, loader, file) {
    if (glbCache[file]) return glbCache[file];
    glbCache[file] = new Promise(function (res, rej) {
      loader.load(url(cfg.glb + file), function (g) {
        liftMaterials(THREE, g.scene);
        res(g.scene);
      }, undefined, function (e) { rej(e); });
    });
    return glbCache[file];
  }

  // --------------------------------------------------------------------------
  // the instance
  // --------------------------------------------------------------------------
  var active = null;

  function mount(el, opts) {
    opts = opts || {};
    if (!el) return Promise.reject(new Error('hub-builder-3d: no container'));
    return Promise.all([loadThree(), loadManifest()]).then(function (out) {
      var inst = new Stage(out[0], out[1], el, opts);
      active = inst;
      return inst.init();
    });
  }

  function Stage(THREE, manifest, el, opts) {
    this.T = THREE;
    this.manifest = manifest;
    this.el = el;
    this.opts = opts;
    this.gunId = opts.gunId;
    this.items = opts.items || {};
    this.art = opts.art || null;          // 2D composite art; unused in the pilot
    this.onSelectSlot = typeof opts.onSelectSlot === 'function' ? opts.onSelectSlot : null;
    this.fitted = new Map();              // slotPath -> {key, obj, socket, ghost}
    this.socketOf = new Map();            // slotPath -> socket Object3D
    this.disposed = false;
    this.dirty = true;
    this.raf = 0;
    this.view = 'side';
    this.highlighted = null;
    this.tree = opts.tree || [];
  }

  Stage.prototype.init = function () {
    var T = this.T, self = this;
    var gun = this.manifest.guns[this.gunId];
    if (!gun) return Promise.reject(new Error('no 3D for gun ' + this.gunId));
    this.gun = gun;

    var host = document.createElement('div');
    host.className = 'wb-3d-host';
    host.style.cssText = 'position:relative;width:100%;height:100%;min-height:220px;touch-action:none;';
    this.el.appendChild(host);
    this.host = host;

    var r = new T.WebGLRenderer({ antialias: true, alpha: false, powerPreference: 'high-performance' });
    r.setPixelRatio(Math.min(2, (window.devicePixelRatio || 1)));   // cap: phones
    r.outputColorSpace = T.SRGBColorSpace;
    r.toneMapping = T.ACESFilmicToneMapping;
    r.toneMappingExposure = 1.35;   // phone-in-daylight, not studio-dark
    r.domElement.style.cssText = 'display:block;width:100%;height:100%;';
    host.appendChild(r.domElement);
    this.renderer = r;

    var scene = new T.Scene();
    scene.background = this.gradient(T, '#0d1116', '#05070a');
    this.scene = scene;

    // studio lighting: key over the shooter's shoulder, rim from behind the
    // muzzle to pop the top rail, soft hemisphere fill so nothing goes to pure
    // black, plus a tiny procedural environment so the metals are not matte.
    // The key was 0xfff4e8 at 4.4. That warm tint plus the exposure below is
    // what turned the AK's dark bakelite furniture salmon on screen no matter
    // what albedo the generator authored - a warm light multiplying a red-brown
    // albedo pushes R to clip long before G and B get there. Neutral key, and
    // the furniture's colour is now the generator's business alone.
    var key = new T.DirectionalLight(0xffffff, 4.4); key.position.set(-0.4, 0.9, 0.9);
    var rim = new T.DirectionalLight(0xcfe2ff, 2.8); rim.position.set(0.9, -0.7, 0.5);
    var kick = new T.DirectionalLight(0xffffff, 1.6); kick.position.set(-0.5, 0.3, -0.8);
    var fill = new T.HemisphereLight(0xa8bcd6, 0x1b2029, 1.6);
    scene.add(key, rim, kick, fill);
    this.env(T, scene, r);

    // 26 deg, not the usual 50: a 0.84 m object 0.9 m away under a wide lens
    // fish-eyes into an SMG. A long lens keeps the side view catalogue-flat.
    // 15 deg, not 26 and certainly not the usual 50: at 26 the 0.94 m rifle
    // still perspective-shrinks toward the muzzle, which is the opposite of
    // the flat catalogue side elevation the 2D stage draws. 15 deg is close
    // enough to orthographic that the muzzle end and the butt end read at the
    // same scale, and fitToContent solves the distance for it either way.
    var cam = new T.PerspectiveCamera(15, 1, 0.01, 20);
    cam.up.set(0, 0, 1);                       // Z-up world; see 3d/manifest.json
    this.camera = cam;

    var controls = new T.OrbitControls(cam, r.domElement);
    controls.enableDamping = true;
    controls.dampingFactor = 0.085;
    controls.enablePan = false;
    controls.rotateSpeed = 0.85;
    controls.zoomSpeed = 0.8;
    controls.minDistance = (gun.view && gun.view.minRadius) || 0.22;
    controls.maxDistance = (gun.view && gun.view.maxRadius) || 1.6;
    controls.addEventListener('change', function () { self.invalidate(); });
    controls.addEventListener('start', function () { self.userMoved = true; });
    this.controls = controls;

    this.root = new T.Group();
    scene.add(this.root);

    this.bindResize();
    this.bindPointer();
    this.setView('side');

    return loadGlb(T, this.loader(), gun.file).then(function (scene0) {
      if (self.disposed) return self;
      self.chassis = scene0.clone(true);
      self.root.add(self.chassis);
      self.indexSockets();
      return self.update(self.tree);
    }).then(function () {
      self.userMoved = false;
      self.fitToContent(false);
      return self;
    });
  };

  Stage.prototype.loader = function () {
    if (this._loader) return this._loader;
    var T = this.T;
    // NO decoder is attached on purpose. meshopt and draco both decode through
    // WebAssembly, and the island shell CSP is script-src 'self'
    // 'unsafe-inline' (2026-09-10 hardening), under which
    // WebAssembly.instantiate throws - which is exactly how this blew up in the
    // real build. The GLBs ship KHR_mesh_quantization instead, which GLTFLoader
    // handles natively. Do not re-add a decoder without changing the CSP.
    var l = new T.GLTFLoader();
    this._loader = l;
    return l;
  };

  // vertical gradient background, matching the 2D stage's dark plate
  Stage.prototype.gradient = function (T, top, bottom) {
    var c = document.createElement('canvas');
    c.width = 2; c.height = 256;
    var g = c.getContext('2d');
    var grad = g.createLinearGradient(0, 0, 0, 256);
    grad.addColorStop(0, top); grad.addColorStop(1, bottom);
    g.fillStyle = grad; g.fillRect(0, 0, 2, 256);
    var tex = new T.CanvasTexture(c);
    tex.colorSpace = T.SRGBColorSpace;
    this._bgTex = tex;
    return tex;
  };

  // A 4-band equirect "studio" so metallic surfaces have something to reflect.
  // Without this, metalness 0.9 renders as near-black under lights alone.
  Stage.prototype.env = function (T, scene, renderer) {
    var c = document.createElement('canvas');
    c.width = 64; c.height = 32;
    var g = c.getContext('2d');
    var grad = g.createLinearGradient(0, 0, 0, 32);
    grad.addColorStop(0.00, '#e8eef6');
    grad.addColorStop(0.42, '#8e9bab');
    grad.addColorStop(0.52, '#3b434e');
    grad.addColorStop(1.00, '#10141a');
    g.fillStyle = grad; g.fillRect(0, 0, 64, 32);
    g.fillStyle = 'rgba(255,255,255,0.95)'; g.fillRect(6, 2, 22, 7);
    var tex = new T.CanvasTexture(c);
    tex.mapping = T.EquirectangularReflectionMapping;
    tex.colorSpace = T.SRGBColorSpace;
    var pmrem = new T.PMREMGenerator(renderer);
    this._envRT = pmrem.fromEquirectangular(tex);
    scene.environment = this._envRT.texture;
    scene.environmentIntensity = 1.30;
    tex.dispose();
    pmrem.dispose();
  };

  // --------------------------------------------------------------------------
  // sockets
  // --------------------------------------------------------------------------
  Stage.prototype.findSocket = function (holder, nameId) {
    var hit = null;
    holder.traverse(function (o) {
      if (!hit && o.name === nameId) hit = o;
    });
    return hit;
  };

  Stage.prototype.indexSockets = function () {
    // the chassis owns the root-level sockets; attached parts own theirs. This
    // is rebuilt lazily inside update(), so nothing caches a stale node.
    this.socketOf.clear();
  };

  // Map EVERY slot in the current tree to its 3D anchor - empty slots included,
  // because the card / leader-line layer has to point at an empty magazine well
  // just as much as at a fitted magazine. Run after each update() settles.
  Stage.prototype.reindexSockets = function () {
    var self = this;
    this.socketOf.clear();
    if (!this.chassis) return;
    this.tree.forEach(function (n) {
      if (!n || !n.nameId) return;
      var holder = self.holderFor(n.parentPath);
      if (!holder) return;
      var s = self.findSocket(holder, n.nameId);
      if (s) self.socketOf.set(n.path, s);
    });
  };

  // Which Object3D should we search for `nameId`? The parent's fitted part if
  // there is one (nested sockets ride with the part), otherwise the chassis -
  // which is also the right answer for chassis slots like mod_barrel, whose
  // children are baked into the gun mesh.
  Stage.prototype.holderFor = function (parentPath) {
    if (parentPath && this.fitted.has(parentPath)) {
      var f = this.fitted.get(parentPath);
      if (f && f.obj) return f.obj;
    }
    return this.chassis;
  };

  // --------------------------------------------------------------------------
  // update - the whole point of the module
  // --------------------------------------------------------------------------
  Stage.prototype.update = function (tree) {
    var self = this, T = this.T;
    this.tree = Array.isArray(tree) ? tree : [];
    if (!this.chassis) return Promise.resolve(this);

    var gun = this.gun;
    var chassisSlots = gun.chassisSlots || [];
    var defaults = gun.defaultParts || {};

    // 1. decide what SHOULD be on the gun
    var want = new Map();      // slotPath -> {key|null, nameId, item}
    this.tree.forEach(function (n) {
      if (!n || !n.nameId) return;
      if (chassisSlots.indexOf(n.nameId) >= 0) return;     // baked into the mesh
      var item = n.item ? (self.items[n.item] || null) : null;
      var key = null;
      if (n.item) key = resolveArchetype(self.manifest, n.nameId, item, gun);
      else if (defaults[n.nameId] && !n.parentPath) key = defaults[n.nameId];
      else if (defaults[n.nameId] && chassisSlots.indexOf(lastSeg(n.parentPath)) >= 0) key = defaults[n.nameId];
      if (!key && !n.item) return;                          // empty slot, no default
      want.set(n.path, { key: key, nameId: n.nameId, item: n.item || null, node: n });
    });

    // 2. drop anything no longer wanted (or whose archetype changed)
    var stale = [];
    this.fitted.forEach(function (f, p) {
      var w = want.get(p);
      if (!w || w.key !== f.key) stale.push(p);
    });
    // remove deepest-first so a parent removal does not orphan a live child map
    stale.sort(function (a, b) { return b.split('/').length - a.split('/').length; });
    stale.forEach(function (p) { self.detach(p); });
    // a removed parent invalidates every descendant
    this.fitted.forEach(function (f, p) {
      var alive = p.indexOf('/') < 0 || self.fitted.has(p.slice(0, p.lastIndexOf('/')))
        || chassisSlots.indexOf(lastSeg(p.slice(0, p.lastIndexOf('/')))) >= 0;
      if (!alive) stale.push(p);
    });
    stale.forEach(function (p) { if (self.fitted.has(p)) self.detach(p); });

    // 3. attach shallow-first, so a part's own sockets exist before its
    //    children are resolved (handguard -> foregrip, scope -> mount, ...)
    var byDepth = Array.from(want.keys()).sort(function (a, b) {
      return a.split('/').length - b.split('/').length;
    });

    var chain = Promise.resolve();
    byDepth.forEach(function (p) {
      chain = chain.then(function () {
        if (self.disposed || self.fitted.has(p)) return null;
        return self.attach(p, want.get(p));
      });
    });
    return chain.then(function () {
      self.reindexSockets();
      if (self.highlighted) self.highlightSlot(self.highlighted);
      // the silhouette just changed - a suppressor or a drum is 100 mm of new
      // extent, so re-frame (keeping the user's angle if they have orbited)
      self.fitToContent(true);
      self.invalidate();
      return self;
    });
  };

  Stage.prototype.attach = function (path, w) {
    var self = this, T = this.T;
    var node = w.node;
    var holder = this.holderFor(node.parentPath);
    var socket = holder ? this.findSocket(holder, w.nameId) : null;
    if (!socket) return null;                  // no anchor in the blockout: skip
    this.socketOf.set(path, socket);

    if (!w.key) {                              // UNMAPPED -> labelled ghost box
      var ghost = this.makeGhost(w.item);
      socket.add(ghost);
      this.fitted.set(path, { key: null, obj: ghost, socket: socket, ghost: true, itemId: w.item });
      return null;
    }
    var arch = this.manifest.archetypes[w.key];
    if (!arch) return null;
    return loadGlb(T, this.loader(), arch.file).then(function (proto) {
      if (self.disposed) return;
      // re-check: a fast click sequence can land two attaches on one path
      if (self.fitted.has(path)) return;
      var obj = proto.clone(true);
      obj.userData.slotPath = path;
      obj.traverse(function (o) { o.userData.slotPath = path; });
      socket.add(obj);
      self.fitted.set(path, { key: w.key, obj: obj, socket: socket, ghost: false, itemId: w.item });
      self.invalidate();
    });
  };

  Stage.prototype.makeGhost = function (itemId) {
    var T = this.T;
    var g = (this.manifest.ghost || {});
    var s = g.size || [0.075, 0.055, 0.045];
    if (!this._ghostGeo) {
      // grown along the socket's +Y so it reads as "something mounts here"
      this._ghostGeo = new T.BoxGeometry(s[0], s[1], s[2]);
      this._ghostGeo.translate(0, s[1] * 0.5, 0);
      this._ghostMat = new T.MeshStandardMaterial({
        color: new T.Color(g.color || '#7bd0ff'),
        transparent: true, opacity: g.opacity == null ? 0.28 : g.opacity,
        roughness: 0.4, metalness: 0.0, depthWrite: false,
      });
      this._ghostEdgeMat = new T.LineBasicMaterial({ color: new T.Color(g.color || '#7bd0ff') });
      this._ghostEdgeGeo = new T.EdgesGeometry(this._ghostGeo);
    }
    var mesh = new T.Mesh(this._ghostGeo, this._ghostMat);
    mesh.add(new T.LineSegments(this._ghostEdgeGeo, this._ghostEdgeMat));
    mesh.userData.ghostFor = itemId || null;
    return mesh;
  };

  Stage.prototype.detach = function (path) {
    var f = this.fitted.get(path);
    if (!f) return;
    if (f.obj && f.obj.parent) f.obj.parent.remove(f.obj);
    if (!f.ghost) disposeTree(this.T, f.obj);     // clones own their materials
    this.fitted.delete(path);
    this.socketOf.delete(path);
    this.invalidate();
  };

  // --------------------------------------------------------------------------
  // highlight
  // --------------------------------------------------------------------------
  Stage.prototype.highlightSlot = function (path) {
    var T = this.T;
    if (this._halo && this._halo.parent) this._halo.parent.remove(this._halo);
    this.highlighted = path || null;
    if (!path) { this.invalidate(); return this; }
    var socket = this.socketOf.get(path);
    if (!socket) { this.invalidate(); return this; }
    if (!this._halo) {
      var geo = new T.TorusGeometry(0.030, 0.0035, 8, 28);
      geo.rotateX(Math.PI / 2);                        // ring lies on the +Y face
      this._haloGeo = geo;
      this._haloMat = new T.MeshBasicMaterial({
        color: 0x7bd0ff, transparent: true, opacity: 0.9, depthTest: false,
      });
      this._halo = new T.Mesh(geo, this._haloMat);
      this._halo.renderOrder = 999;
    }
    socket.add(this._halo);
    this.invalidate();
    return this;
  };

  // --------------------------------------------------------------------------
  // projection: where each socket is on screen, for the 2D card / leader layer
  // --------------------------------------------------------------------------
  var _v = null;
  Stage.prototype.socketScreenPositions = function () {
    var T = this.T, out = {}, self = this;
    if (!this.camera || !this.host) return out;
    if (!_v) _v = new T.Vector3();
    var w = this.host.clientWidth || 1, h = this.host.clientHeight || 1;
    this.camera.updateMatrixWorld();
    this.socketOf.forEach(function (socket, path) {
      socket.getWorldPosition(_v);
      _v.project(self.camera);
      var visible = _v.z > -1 && _v.z < 1 && _v.x >= -1.08 && _v.x <= 1.08 && _v.y >= -1.08 && _v.y <= 1.08;
      out[path] = {
        x: (_v.x * 0.5 + 0.5) * w,
        y: (-_v.y * 0.5 + 0.5) * h,
        visible: visible,
      };
    });
    return out;
  };

  Stage.prototype.markerPositions = Stage.prototype.socketScreenPositions;

  // The assembled weapon's screen-space box, as a fraction of the host. Exposed
  // so a verifier can assert the framing instead of eyeballing a screenshot.
  Stage.prototype.modelScreenBox = function () {
    var T = this.T;
    if (!this.root || !this.host) return null;
    var box = new T.Box3().setFromObject(this.root);
    if (box.isEmpty()) return null;
    var w = this.host.clientWidth || 1, h = this.host.clientHeight || 1;
    var v = new T.Vector3(), x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
    this.camera.updateMatrixWorld();
    for (var i = 0; i < 8; i++) {
      v.set(i & 1 ? box.max.x : box.min.x, i & 2 ? box.max.y : box.min.y, i & 4 ? box.max.z : box.min.z);
      v.project(this.camera);
      var sx = (v.x * 0.5 + 0.5) * w, sy = (-v.y * 0.5 + 0.5) * h;
      x0 = Math.min(x0, sx); x1 = Math.max(x1, sx); y0 = Math.min(y0, sy); y1 = Math.max(y1, sy);
    }
    return { x: x0, y: y0, w: x1 - x0, h: y1 - y0, fracW: (x1 - x0) / w, fracH: (y1 - y0) / h };
  };

  // --------------------------------------------------------------------------
  // views
  // --------------------------------------------------------------------------
  // Fit the camera to the bounding box of the WHOLE ASSEMBLED WEAPON.
  //
  // The first version aimed a fixed world radius at a fixed target, which meant
  // the framing was only ever right for the gun it was tuned on: bolt on a
  // suppressor and a drum and the model ran off both edges (measured 0.95 of
  // the width on a phone, 1.15 of the height on a 1920x560 stage). Anything
  // that changes the silhouette - mount, update(), a resize, a rotate - has to
  // re-fit, so the fit is computed from the real Box3 every time.
  //
  // Exact, not a bounding sphere: a bounding sphere around a 0.84 m rifle is
  // 0.44 m in every direction and would frame the gun at about half the size it
  // could be. The 8 box corners are projected onto the camera's own right/up/
  // forward axes and the distance solved per axis against the real FOVs.
  Stage.prototype.fitToContent = function (keepAngle) {
    var T = this.T;
    if (!this.root || !this.camera || !this.controls) return this;
    var box = new T.Box3().setFromObject(this.root);
    if (!isFinite(box.min.x) || box.isEmpty()) return this;

    var centre = box.getCenter(new T.Vector3());
    // Default eye: a TRUE SIDE elevation off the gun's LEFT (+Y), 12 deg up.
    // The old vector carried a -0.16 X term and 24 deg of elevation, which is
    // a rear three-quarter: the butt sat nearest the lens and the muzzle fell
    // away down the barrel. The 2D stage draws a flat side elevation, so the
    // 3D default has to be the same shot. X is exactly 0 so neither end is
    // nearer the camera; +X - the muzzle - still lands on the LEFT of the
    // screen because right = worldUp x dir comes out as -X.
    var dir;
    if (keepAngle && this.userMoved) {
      dir = this.camera.position.clone().sub(this.controls.target);
      if (dir.lengthSq() < 1e-9) dir = new T.Vector3(0, 0.9781, 0.2079);
      dir.normalize();
    } else {
      dir = new T.Vector3(0, 0.9781, 0.2079).normalize();   // 12 deg elevation
    }
    var worldUp = new T.Vector3(0, 0, 1);
    var right = new T.Vector3().crossVectors(worldUp, dir).normalize();
    if (!isFinite(right.x) || right.lengthSq() < 1e-6) right.set(1, 0, 0);
    var camUp = new T.Vector3().crossVectors(dir, right).normalize();

    var eR = 0, eU = 0, eF = 0, v = new T.Vector3();
    for (var i = 0; i < 8; i++) {
      v.set(i & 1 ? box.max.x : box.min.x,
        i & 2 ? box.max.y : box.min.y,
        i & 4 ? box.max.z : box.min.z).sub(centre);
      eR = Math.max(eR, Math.abs(v.dot(right)));
      eU = Math.max(eU, Math.abs(v.dot(camUp)));
      eF = Math.max(eF, Math.abs(v.dot(dir)));
    }
    var fovY = this.camera.fov * Math.PI / 180;
    var fovX = 2 * Math.atan(Math.tan(fovY / 2) * (this.camera.aspect || 1));
    var d = Math.max(eR / Math.tan(fovX / 2), eU / Math.tan(fovY / 2)) + eF;
    // 25%, not 8%. At 8% the rifle ran muzzle-to-butt across 92% of the canvas
    // width with the leader-line labels overhanging both ends. 25% lands the
    // model at ~0.80 of the canvas width, which is the framing the 2D stage
    // uses and leaves room for the labels.
    d *= 1.25;
    d = Math.max(d, 0.05);

    this.fitDist = d;
    this.controls.target.copy(centre);
    this.camera.position.copy(centre).addScaledVector(dir, d);
    this.camera.near = Math.max(0.004, d * 0.02);
    this.camera.far = d * 12;
    this.camera.updateProjectionMatrix();
    this.controls.minDistance = d * 0.6;           // zoom range 0.6x - 2.5x
    this.controls.maxDistance = d * 2.5;
    this.controls.update();
    this.invalidate();
    return this;
  };

  Stage.prototype.setView = function (which) {
    this.view = which === 'free' ? 'free' : 'side';
    if (this.view === 'side') this.userMoved = false;   // snap back to the fit
    return this.fitToContent(this.view === 'free');
  };

  // --------------------------------------------------------------------------
  // loop / resize / pointer
  // --------------------------------------------------------------------------
  Stage.prototype.invalidate = function () {
    this.dirty = true;
    if (!this.raf && !this.disposed) {
      var self = this;
      this.raf = requestAnimationFrame(function tick() {
        if (self.disposed) { self.raf = 0; return; }
        var moving = self.controls.update();       // true while damping settles
        if (self.dirty || moving) {
          self.renderer.render(self.scene, self.camera);
          self.dirty = false;
          self.raf = requestAnimationFrame(tick);
        } else {
          self.raf = 0;                            // idle: stop burning frames
        }
      });
    }
  };

  Stage.prototype.resize = function () {
    if (!this.host || !this.renderer) return;
    var w = this.host.clientWidth || 1, h = this.host.clientHeight || 1;
    this.renderer.setSize(w, h, false);
    this.camera.aspect = w / h;
    this.camera.updateProjectionMatrix();
    // re-frame on rotate / sheet resize; the ANGLE is kept if the user has
    // orbited, but the distance is always re-solved for the new aspect
    this.fitToContent(true);
    this.invalidate();
  };

  Stage.prototype.bindResize = function () {
    var self = this;
    this._onWinResize = function () { self.resize(); };
    window.addEventListener('resize', this._onWinResize);
    if (typeof ResizeObserver !== 'undefined') {
      this._ro = new ResizeObserver(function () { self.resize(); });
      this._ro.observe(this.host);
    }
    this.resize();
  };

  var _ray = null, _ptr = null;
  Stage.prototype.bindPointer = function () {
    var self = this, T = this.T;
    var downX = 0, downY = 0, downT = 0;
    this._onDown = function (e) { downX = e.clientX; downY = e.clientY; downT = Date.now(); };
    this._onUp = function (e) {
      if (!self.onSelectSlot) return;
      var dx = e.clientX - downX, dy = e.clientY - downY;
      if (dx * dx + dy * dy > 36 || Date.now() - downT > 600) return;   // a drag
      var r = self.renderer.domElement.getBoundingClientRect();
      if (!_ray) { _ray = new T.Raycaster(); _ptr = new T.Vector2(); }
      _ptr.set(((e.clientX - r.left) / r.width) * 2 - 1,
        -((e.clientY - r.top) / r.height) * 2 + 1);
      _ray.setFromCamera(_ptr, self.camera);
      var hits = _ray.intersectObject(self.root, true);
      for (var i = 0; i < hits.length; i++) {
        var o = hits[i].object;
        while (o && !o.userData.slotPath && o !== self.root) o = o.parent;
        if (o && o.userData.slotPath) { self.onSelectSlot(o.userData.slotPath); return; }
      }
      self.onSelectSlot(null);
    };
    this.renderer.domElement.addEventListener('pointerdown', this._onDown);
    this.renderer.domElement.addEventListener('pointerup', this._onUp);
  };

  // --------------------------------------------------------------------------
  // teardown - a WebGL context that is not released survives the route change
  // --------------------------------------------------------------------------
  function disposeTree(T, obj) {
    if (!obj) return;
    obj.traverse(function (o) {
      if (o.geometry) o.geometry.dispose();
      var m = o.material;
      if (!m) return;
      (Array.isArray(m) ? m : [m]).forEach(function (mm) {
        for (var k in mm) {
          if (mm[k] && mm[k].isTexture) mm[k].dispose();
        }
        mm.dispose();
      });
    });
  }

  Stage.prototype.destroy = function () {
    if (this.disposed) return;
    this.disposed = true;
    if (this.raf) cancelAnimationFrame(this.raf);
    this.raf = 0;
    if (this._onWinResize) window.removeEventListener('resize', this._onWinResize);
    if (this._ro) this._ro.disconnect();
    if (this.renderer) {
      this.renderer.domElement.removeEventListener('pointerdown', this._onDown);
      this.renderer.domElement.removeEventListener('pointerup', this._onUp);
    }
    if (this.controls) this.controls.dispose();
    disposeTree(this.T, this.root);
    if (this._ghostGeo) this._ghostGeo.dispose();
    if (this._ghostEdgeGeo) this._ghostEdgeGeo.dispose();
    if (this._haloGeo) this._haloGeo.dispose();
    if (this._bgTex) this._bgTex.dispose();
    if (this._envRT) this._envRT.dispose();
    if (this.renderer) {
      this.renderer.dispose();
      if (this.renderer.domElement.parentNode) {
        this.renderer.domElement.parentNode.removeChild(this.renderer.domElement);
      }
    }
    if (this.host && this.host.parentNode) this.host.parentNode.removeChild(this.host);
    this.fitted.clear();
    this.socketOf.clear();
    if (active === this) active = null;
  };

  // --------------------------------------------------------------------------
  // module surface. Instance methods are also exposed at module level, acting
  // on the most recently mounted stage, so T1 can call either shape.
  // --------------------------------------------------------------------------
  function delegate(name) {
    return function () {
      if (!active) return name === 'socketScreenPositions' || name === 'markerPositions' ? {} : null;
      return active[name].apply(active, arguments);
    };
  }

  return {
    mount: mount,
    ready: ready,
    supports: supports,
    configure: configure,
    update: delegate('update'),
    highlightSlot: delegate('highlightSlot'),
    socketScreenPositions: delegate('socketScreenPositions'),
    markerPositions: delegate('markerPositions'),
    setView: delegate('setView'),
    resize: delegate('resize'),
    destroy: delegate('destroy'),
    instance: function () { return active; },
    // exported for the test page + any future unit test
    _pure: { slotKey: slotKey, resolveArchetype: resolveArchetype, lastSeg: lastSeg },
  };
}));
